#!/usr/bin/env bash
#
# Build the disk image the file explorer browses: 64MiB with an MBR and a
# single FAT32 partition starting 1MiB in, holding a sample tree a few
# folders deep - long and mixed-case names, an empty folder, an empty file,
# a folder with more entries than fit on one screen, and files that span
# many clusters.
#
# Every run produces the same tree with the same contents. The image is a
# build product, so regenerate it rather than editing it.
#
# usage: tools/mkdisk.sh [IMAGE]      (default ./disk.img)
#
# Needs mkfs.fat (dosfstools), mtools and sfdisk (util-linux).

set -eu

OUT="${1:-disk.img}"

SIZE_MIB=64
PART_START=2048				# in sectors: 1MiB
PART_SECTORS=$(( SIZE_MIB * 2048 - PART_START ))

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

PART="$TMP/part.img"

# mtools otherwise balks at a geometry that is not a whole number of tracks
export MTOOLS_SKIP_CHECK=1

# One sector per cluster: even small files and folders then span several
# clusters, so reading anything means following a cluster chain
mkfs.fat -F 32 -s 1 -n OS3DISK -i 0053334f -h "$PART_START" --invariant \
	-C "$PART" $(( PART_SECTORS / 2 )) >/dev/null

# Entries are listed in the order they were created, so the order below is
# the order the explorer shows them in
folder() {
	mmd -i "$PART" "::$1"
}

# file PATH - contents on stdin
file() {
	cat >"$TMP/content"
	mcopy -i "$PART" "$TMP/content" "::$1"
}

folder "/DOCS"
folder "/SRC"
folder "/Photos"
folder "/Empty Folder"

file "/README.TXT" <<'EOF'
OS3 sample disk

This volume is generated by tools/mkdisk.sh. Browse it with the file
explorer: click a folder to open it, Up to go back.
EOF

file "/Welcome to OS3.txt" <<'EOF'
Welcome to OS3!

This disk is a FAT32 volume inside an MBR partition. The kernel finds it
through its AHCI driver, reads the partition table, mounts the volume and
hands it to the file explorer you are looking at.

Folders open with a single click. The Up button goes back to the parent
folder, and Prev / Next page through folders too big for one screen.
Clicking a file reads the whole of it and shows its first bytes below.
EOF

seq 1 100000 | head -c 204800 | file "/bigfile.bin"

file "/DOCS/Getting Started.md" <<'EOF'
# Getting started

1. Build the kernel and the ISO: `make iso`
2. Build this disk: `make disk.img`
3. Boot both under QEMU: `make run`

The explorer starts in the root folder of the first FAT volume it finds.
EOF

file "/DOCS/License.txt" <<'EOF'
Sample files for OS3. Do whatever you like with them.
EOF

folder "/DOCS/notes"

file "/DOCS/notes/Meeting Notes 2026-09-01.txt" <<'EOF'
Attendees: everyone
- AHCI driver reads sectors now
- FAT32 mounts from the first partition
- File explorer next
EOF

file "/DOCS/notes/ideas.txt" <<'EOF'
Ideas: write support, a text viewer, keyboard navigation.
EOF

file "/DOCS/notes/empty.txt" </dev/null

file "/DOCS/notes/A very long file name that needs several LFN entries.txt" <<'EOF'
Long file names are stored thirteen characters at a time.
EOF

folder "/DOCS/notes/2026"

file "/DOCS/notes/2026/todo.txt" <<'EOF'
Fix the AHCI driver
Write a FAT32 driver
Build a file explorer
EOF

yes "September: ship the file explorer, then write support." \
	| head -c 3000 | file "/DOCS/notes/2026/September Plans.txt"

folder "/DOCS/notes/2026/archive"

file "/DOCS/notes/2026/archive/Q1 Review.txt" <<'EOF'
Q1: got the kernel booting again on a modern toolchain.
EOF

file "/SRC/Makefile" <<'EOF'
all:
	make -C kernel
EOF

folder "/SRC/kernel"

file "/SRC/kernel/main.c" <<'EOF'
int main(void)
{
	return 0;
}
EOF

folder "/SRC/kernel/drivers"

yes "/* ahci */" | head -c 8000 | file "/SRC/kernel/drivers/ahci.c"
yes "/* fat */" | head -c 12000 | file "/SRC/kernel/drivers/fat.c"

for i in $(seq -w 1 45); do
	yes "Photo $i" | head -c $(( 700 + 10#$i * 613 )) \
		| file "/Photos/Holiday 2026 - $i.jpg"
done

# Put the partition inside a disk with an MBR describing it
rm -f "$OUT.tmp"
truncate -s "${SIZE_MIB}M" "$OUT.tmp"

sfdisk --quiet "$OUT.tmp" <<EOF
label: dos
label-id: 0x0053334f
start=$PART_START, size=$PART_SECTORS, type=c
EOF

dd if="$PART" of="$OUT.tmp" bs=512 seek="$PART_START" conv=notrunc status=none

mv "$OUT.tmp" "$OUT"
